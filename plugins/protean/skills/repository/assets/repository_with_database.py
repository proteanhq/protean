# Example usage
if __name__ == "__main__":
    domain.init(traverse=False)

    with domain.domain_context():
        repo = domain.repository_for(Report)

        # Add reports
        repo.add(
            Report(
                report_id="RPT-001",
                title="Q4 Sales Report",
                report_type="sales",
                generated_by="analyst-1",
                total_value=1250000.00,
            )
        )
        repo.add(
            Report(
                report_id="RPT-002",
                title="Monthly Expense Report",
                report_type="expenses",
                generated_by="analyst-2",
                total_value=85000.00,
            )
        )

        # Use custom queries
        sales_reports = repo.find_by_type("sales")
        print(f"Sales reports: {len(sales_reports)}")

        analyst_reports = repo.find_by_author("analyst-1")
        print(f"Reports by analyst-1: {len(analyst_reports)}")
