"""
Database-specific repository binding.

This example demonstrates:
- Using the database option to bind a repository to a specific database type
- Default repository uses database="ALL" (works with any database)
- Custom repository can be locked to a specific database (e.g., "postgresql", "sqlite")
- Multiple repositories per aggregate for different databases
- Database-specific query optimizations

Usage:
    # The domain automatically selects the correct repository
    # based on the provider's database type
    repo = domain.repository_for(Report)
"""

from protean import Domain
from protean.fields import Float, Identifier, String

# Domain setup
domain = Domain()


@domain.aggregate
class Report:
    """Report aggregate for analytics."""

    report_id: Identifier(identifier=True)
    title: String(required=True, max_length=200)
    report_type: String(required=True)
    generated_by: String(required=True)
    total_value: Float(default=0.0)


@domain.repository(part_of=Report)
class ReportRepository:
    """Generic repository for Report aggregate.

    This repository works with ALL databases (default behavior).
    It provides domain-specific query methods that use the standard
    DAO query interface, which works across all database providers.

    When the database option is "ALL" (default), this repository
    is used regardless of which database provider is active.
    """

    def find_by_type(self, report_type: str):
        """Find all reports of a given type."""
        return self.query.filter(report_type=report_type).all()

    def find_by_author(self, author: str):
        """Find all reports generated by a specific author."""
        return self.query.filter(generated_by=author).all()


