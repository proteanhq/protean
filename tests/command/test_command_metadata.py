def test_command_metadata(test_domain):
    identifier = str(uuid4())
    command = test_domain._enrich_command(Login(user_id=identifier), True)

    # Compute expected checksum
    expected_checksum = MessageEnvelope.compute_checksum(command.payload)

    command_dict = command.to_dict()

    # correlation_id is auto-generated by _enrich_command — verify it's a non-empty hex string
    generated_correlation_id = command_dict["_metadata"]["domain"]["correlation_id"]
    assert generated_correlation_id is not None
    assert len(generated_correlation_id) == 32  # UUID4 hex, no dashes

    assert command_dict == {
        "_metadata": {
            "domain": {
                "fqn": fqn(Login),
                "kind": "COMMAND",
                "origin_stream": None,
                "stream_category": None,
                "version": 1,
                "sequence_id": None,
                "asynchronous": True,
                "expected_version": None,
                "priority": 0,
                "correlation_id": generated_correlation_id,
                "causation_id": None,
            },
            "envelope": {
                "specversion": "1.0",
                "checksum": expected_checksum,
            },
            "headers": {
                "id": f"{identifier}",
                "type": "Test.Login.v1",
                "stream": f"test::user:command-{identifier}",
                "time": command._metadata.headers.time.isoformat(),
                "traceparent": None,
                "idempotency_key": None,
                "deadline": None,
            },
            "event_store": None,
            "extensions": {},
        },
        "user_id": command.user_id,
    }


class TestCommandEnvelope:
    def test_enrich_command_adds_envelope_with_checksum(self, test_domain):
        """Test that _enrich_command adds envelope with correct checksum"""
        identifier = str(uuid4())
        command = Login(user_id=identifier)

        enriched_command = test_domain._enrich_command(command, True)

        # Verify envelope exists
        assert enriched_command._metadata.envelope is not None
        assert enriched_command._metadata.envelope.specversion == "1.0"

        # Verify checksum is computed correctly
        expected_checksum = MessageEnvelope.compute_checksum(enriched_command.payload)
        assert enriched_command._metadata.envelope.checksum == expected_checksum

    def test_command_envelope_checksum_changes_with_payload(self, test_domain):
        """Test that different payloads produce different checksums"""
        command1 = Login(user_id=str(uuid4()))
        command2 = Login(user_id=str(uuid4()))

        enriched1 = test_domain._enrich_command(command1, True)
        enriched2 = test_domain._enrich_command(command2, True)

        # Different payloads should have different checksums
        assert (
            enriched1._metadata.envelope.checksum
            != enriched2._metadata.envelope.checksum
        )

    def test_command_envelope_checksum_consistent_for_same_payload(self, test_domain):
        """Test that same payload always produces same checksum"""
        identifier = str(uuid4())
        command1 = Login(user_id=identifier)
        command2 = Login(user_id=identifier)

        enriched1 = test_domain._enrich_command(command1, True)
        enriched2 = test_domain._enrich_command(command2, True)

        # Same payload should have same checksum
        assert (
            enriched1._metadata.envelope.checksum
            == enriched2._metadata.envelope.checksum
        )


def _root_command(test_domain, **trace_ids):
    command = test_domain._command_processor.enrich(
        Login(user_id=str(uuid4())), asynchronous=True
    )
    if not trace_ids:
        return command
    domain = command._metadata.domain.model_copy(update=trace_ids)
    metadata = command._metadata.model_copy(update={"domain": domain})
    return Login(command.payload, _metadata=metadata)


@contextmanager
def _in_context(message):
    g.message_in_context = message
    try:
        yield message
    finally:
        g.pop("message_in_context", None)


def _other_message(test_domain):
    return Message.from_domain_object(
        _root_command(test_domain, correlation_id="corr-X", causation_id="cause-X")
    )


class TestTraceIdsOnRebuildFromStoredMessage:
    def test_root_command_keeps_empty_causation_id(self, test_domain):
        root = _root_command(test_domain)
        stored_correlation_id = root._metadata.domain.correlation_id
        assert stored_correlation_id is not None
        assert root._metadata.domain.causation_id is None
        stored = Message.from_domain_object(root)

        with _in_context(_other_message(test_domain)):
            rebuilt = stored.to_domain_object()

        assert rebuilt._metadata.domain.correlation_id == stored_correlation_id
        assert rebuilt._metadata.domain.causation_id is None

    def test_root_command_keeps_both_empty_trace_ids(self, test_domain):
        stored = Message.from_domain_object(
            _root_command(test_domain, correlation_id=None, causation_id=None)
        )

        with _in_context(_other_message(test_domain)):
            rebuilt = stored.to_domain_object()

        assert rebuilt._metadata.domain.correlation_id is None
        assert rebuilt._metadata.domain.causation_id is None

    def test_message_in_context_does_not_cause_itself(self, test_domain):
        stored = Message.from_domain_object(_root_command(test_domain))

        with _in_context(stored):
            rebuilt = stored.to_domain_object()

        assert stored.metadata.headers.id is not None
        assert rebuilt._metadata.domain.causation_id != stored.metadata.headers.id
        assert rebuilt._metadata.domain.causation_id is None

    def test_direct_construction_still_inherits_context_trace_ids(self, test_domain):
        root = _root_command(test_domain, correlation_id=None, causation_id=None)

        with _in_context(_other_message(test_domain)) as other:
            command = Login(root.payload, _metadata=root._metadata)

        assert command._metadata.domain.correlation_id == "corr-X"
        assert command._metadata.domain.causation_id == other.metadata.headers.id

    def test_rebuild_flag_in_template_dict_is_not_a_field(self, test_domain):
        root = _root_command(test_domain)

        with _in_context(_other_message(test_domain)) as other:
            command = Login(
                {**root.payload, "_rebuild": True}, _metadata=root._metadata
            )

        assert command.user_id == root.user_id
        assert "_rebuild" not in command.to_dict()
        # A `_rebuild` key in the template dict does not switch on rebuild
        assert (
            command._metadata.domain.correlation_id
            == root._metadata.domain.correlation_id
        )
        assert command._metadata.domain.causation_id == other.metadata.headers.id


def _with_origin_stream(command, origin_stream):
    message = Message.from_domain_object(command)
    domain = message.metadata.domain.model_copy(update={"origin_stream": origin_stream})
    metadata = message.metadata.model_copy(update={"domain": domain})
    return message.model_copy(update={"metadata": metadata})


def _event_from_stream_b():
    message = Message.from_domain_object(LoggedIn(user_id=str(uuid4())))
    headers = message.metadata.headers.model_copy(update={"stream": "test::stream-b"})
    metadata = message.metadata.model_copy(update={"headers": headers})
    message = message.model_copy(update={"metadata": metadata})
    # Commands built while handling this event take its stream
    assert message.metadata.domain.kind == "EVENT"
    assert message.metadata.headers.stream == "test::stream-b"
    return message


class TestOriginStreamOnRebuildFromStoredMessage:
    def test_empty_stored_origin_stream_stays_empty(self, test_domain):
        stored = _with_origin_stream(_root_command(test_domain), None)
        assert stored.metadata.domain.origin_stream is None

        with _in_context(_event_from_stream_b()):
            rebuilt = stored.to_domain_object()

        assert rebuilt._metadata.domain.origin_stream is None

    def test_stored_origin_stream_wins_over_context(self, test_domain):
        stored = _with_origin_stream(_root_command(test_domain), "test::stream-a")
        assert stored.metadata.domain.origin_stream == "test::stream-a"

        with _in_context(_event_from_stream_b()):
            rebuilt = stored.to_domain_object()

        assert rebuilt._metadata.domain.origin_stream == "test::stream-a"

    def test_stored_origin_stream_kept_with_no_message_in_context(self, test_domain):
        stored = _with_origin_stream(_root_command(test_domain), "test::stream-a")

        rebuilt = stored.to_domain_object()

        assert rebuilt._metadata.domain.origin_stream == "test::stream-a"

    def test_direct_construction_still_takes_origin_stream_from_context(
        self, test_domain
    ):
        root = _root_command(test_domain)

        with _in_context(_event_from_stream_b()):
            command = Login(root.payload, _metadata=root._metadata)

        assert command._metadata.domain.origin_stream == "test::stream-b"

    def test_rebuild_flag_in_template_dict_does_not_keep_origin_stream(
        self, test_domain
    ):
        stored = _with_origin_stream(_root_command(test_domain), "test::stream-a")
        root = stored.to_domain_object()

        with _in_context(_event_from_stream_b()):
            command = Login(
                {**root.payload, "_rebuild": True}, _metadata=root._metadata
            )

        assert command._metadata.domain.origin_stream == "test::stream-b"


class TestStorePositions:
    def test_a_fresh_command_has_no_store_positions(self):
        assert Login(user_id=str(uuid4()))._metadata.event_store is None

    def test_a_command_rebuilt_from_the_store_keeps_its_positions(self, test_domain):
        identifier = str(uuid4())
        test_domain.process(Login(user_id=identifier), asynchronous=True)

        stored = test_domain.event_store.store.read_last_message(
            f"test::user:command-{identifier}"
        )
        assert stored is not None
        assert stored.metadata.event_store is not None
        assert stored.metadata.event_store.position == 0

        command = stored.to_domain_object()

        assert command._metadata.event_store == stored.metadata.event_store
